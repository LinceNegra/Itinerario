function formatarTitulo(
    texto
) {

    const palavrasMinusculas = [

        "a",
        "o",
        "as",
        "os",
        "e",
        "ou",
        "de",
        "da",
        "do",
        "das",
        "dos",
        "em",
        "no",
        "na",
        "nos",
        "nas",
        "com",
        "para",
        "por"

    ];


    return texto
        .toLowerCase()
        .split(" ")
        .map(
            (
                palavra,
                indice
            ) => {

                if (
                    indice > 0 &&
                    palavrasMinusculas.includes(
                        palavra
                    )
                ) {

                    return palavra;

                }


                return (
                    palavra.charAt(0).toUpperCase() +
                    palavra.slice(1)
                );

            }
        )
        .join(" ");

}


