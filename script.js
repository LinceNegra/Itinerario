// =====================================
// CARREGAR PERGUNTA
// =====================================

function carregarPergunta() {

    const item =
        perguntas[
            perguntaAtual
        ];


    const resposta =
        respostas[
            perguntaAtual
        ];


    contador.textContent =
        `Pergunta ${
            perguntaAtual + 1
        } de ${
            perguntas.length
        }`;


    categoriaAtual.textContent =
        item.categoria;


    pergunta.textContent =
        item.pergunta;


    progresso.style.width =
        `${
            (
                (
                    perguntaAtual + 1
                )
                /
                perguntas.length
            )
            *
            100
        }%`;


    alternativas.innerHTML =
        "";


    item.alternativas.forEach(
        (
            alternativa,
            indice
        ) => {


            const botao =
                document.createElement(
                    "button"
                );


            botao.className =
                "alternativa";


            botao.textContent =
                alternativa.texto;


            if (
                resposta === indice
            ) {

                botao.classList.add(
                    "selecionada"
                );

            }


            botao.addEventListener(
                "click",
                () => {


                    respostas[
                        perguntaAtual
                    ] =
                        indice;


                    document
                        .querySelectorAll(
                            ".alternativa"
                        )
                        .forEach(
                            item => {

                                item.classList.remove(
                                    "selecionada"
                                );

                            }
                        );


                    botao.classList.add(
                        "selecionada"
                    );


                    btnProxima.disabled =
                        false;

                }
            );


            alternativas.appendChild(
                botao
            );

        }
    );


    btnVoltar.style.visibility =
        perguntaAtual === 0
            ? "hidden"
            : "visible";


    btnProxima.textContent =
        perguntaAtual ===
        perguntas.length - 1

            ? "Ver resultado"

            : "Próxima";


    btnProxima.disabled =
        resposta === null;

}


// =====================================
// VOLTAR
// =====================================

function voltarPergunta() {

    if (
        perguntaAtual > 0
    ) {

        perguntaAtual--;

        carregarPergunta();

    }

}


// =====================================
// PRÓXIMA
// =====================================

function proximaPergunta() {

    if (
        respostas[
            perguntaAtual
        ] === null
    ) {

        return;

    }


    if (
        perguntaAtual <
        perguntas.length - 1
    ) {

        perguntaAtual++;

        carregarPergunta();

    }

    else {

        gerarResultado();

    }

}


// =====================================
// CALCULAR DADOS
// =====================================

function calcularDados() {

    const categorias =
        {};


    perguntas.forEach(
        (
            item,
            indice
        ) => {


            const respostaIndice =
                respostas[
                    indice
                ];


            if (
                !categorias[
                    item.categoria
                ]
            ) {

                categorias[
                    item.categoria
                ] = {

                    pontos:
                        0,

                    maximo:
                        0

                };

            }


            categorias[
                item.categoria
            ].pontos +=
                item.alternativas[
                    respostaIndice
                ].pontos;


            categorias[
                item.categoria
            ].maximo +=
                3;

        }
    );


    let total =
        0;


    const maximoTotal =
        perguntas.length * 3;


    Object
        .values(
            categorias
        )
        .forEach(
            categoria => {

                total +=
                    categoria.pontos;

            }
        );


    return {

        categorias,

        total,

        maximoTotal

    };

}


// =====================================
// GERAR RESULTADO
// =====================================

function gerarResultado() {

    const dados =
        calcularDados();


    let classificacao;

    let texto;


    // =====================================
    // CLASSIFICAÇÃO
    // =====================================

    if (
        dados.total <= 17
    ) {

        classificacao =
            "Hábitos que precisam de atenção";


        texto =
            "Seu resultado mostra alguns pontos da sua rotina que podem receber mais atenção. Você não precisa mudar tudo de uma vez: escolha pequenos passos que façam sentido para sua realidade.";

    }


    else if (
        dados.total <= 31
    ) {

        classificacao =
            "Bons hábitos";


        texto =
            "Sua rotina apresenta vários hábitos positivos. Existem algumas áreas que podem evoluir gradualmente e fortalecer ainda mais seu cuidado com a saúde e o bem-estar.";

    }


    else if (
        dados.total <= 40
    ) {

        classificacao =
            "Hábitos muito bons";


        texto =
            "Seu resultado mostra uma rotina com muitos hábitos positivos e consistentes. Pequenos ajustes em algumas áreas podem deixar seu cuidado com a saúde ainda mais completo.";

    }


    else {

        classificacao =
            "Hábitos excelentes";


        texto =
            "Seu resultado mostra uma rotina com hábitos muito positivos e consistentes. Continue valorizando o que já funciona e mantendo esses cuidados ao longo do tempo.";

    }


    // =====================================
    // MOSTRAR RESULTADO
    // =====================================

    document
        .getElementById(
            "tituloResultado"
        )
        .textContent =
        formatarTitulo(
            classificacao
        );


    document
        .getElementById(
            "textoResultado"
        )
        .textContent =
        texto;


    document
        .getElementById(
            "pontuacaoGeral"
        )
        .textContent =
        `${dados.total}/${dados.maximoTotal}`;


    mostrarPontosFortes(
        dados.categorias
    );


    mostrarPontosAtencao(
        dados.categorias,
        dados.total,
        dados.maximoTotal
    );


    mostrarDicas(
        dados.categorias,
        dados.total,
        dados.maximoTotal
    );


    criarGrafico(
        dados.categorias
    );


    mostrarMensagemMotivacional(
        dados.categorias,
        dados.total,
        dados.maximoTotal
    );


    mostrarTela(
        telaResultado
    );

}


