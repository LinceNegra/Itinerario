// =====================================
// GRÁFICO RADAR
// =====================================

function criarGrafico(
    categorias
) {

    const ctx =
        document.getElementById(
            "graficoHabitos"
        );


    if (
        grafico
    ) {

        grafico.destroy();

    }


    const nomes =
        Object.keys(
            categorias
        );


    const valores =
        nomes.map(
            nome =>

                Math.round(

                    (
                        categorias[
                            nome
                        ].pontos /

                        categorias[
                            nome
                        ].maximo
                    )

                    *

                    100

                )
        );


    grafico =
        new Chart(
            ctx,
            {

                type:
                    "radar",


                data: {

                    labels:
                        nomes,


                    datasets: [

                        {

                            label:
                                "Seu perfil",

                            data:
                                valores,

                            fill:
                                true,

                            borderWidth:
                                3,

                            pointRadius:
                                5,

                            pointHoverRadius:
                                7

                        }

                    ]

                },


                options: {

                    responsive:
                        true,

                    maintainAspectRatio:
                        true,


                    scales: {

                        r: {

                            beginAtZero:
                                true,

                            min:
                                0,

                            max:
                                100,


                            ticks: {

                                stepSize:
                                    20,

                                backdropColor:
                                    "transparent"

                            },


                            pointLabels: {

                                font: {

                                    size:
                                        13

                                }

                            }

                        }

                    },


                    plugins: {

                        legend: {

                            display:
                                false

                        }

                    }

                }

            }
        );

}


